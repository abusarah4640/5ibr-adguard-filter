def _repair_arabic_catalog() -> None:
    """Repair the legacy catalog that was committed after a UTF-8/CP1252 mix-up."""
    for key, value in tuple(TRANSLATIONS["ar"].items()):
        for encoding in ("cp1256", "cp1252"):
            try:
                repaired = value.encode(encoding).decode("utf-8")
            except (UnicodeEncodeError, UnicodeDecodeError):
                continue
            if any("\u0600" <= character <= "\u06ff" for character in repaired):
                TRANSLATIONS["ar"][key] = repaired
                break


_repair_arabic_catalog()

