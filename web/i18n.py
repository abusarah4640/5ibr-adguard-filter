def _browser_language() -> str | None:
    best = request.accept_languages.best_match(sorted(SUPPORTED_LANGS))
    return best if best in SUPPORTED_LANGS else None


def get_lang() -> str:
    """Resolve language using URL, cookie, session, browser, then English."""
    if not has_request_context():
        return DEFAULT_LANG
    candidates = (
        request.args.get("lang"),
        request.cookies.get("fivebr_lang"),
        session.get("language"),
        _browser_language(),
        DEFAULT_LANG,
    )
    return next(lang for lang in candidates if lang in SUPPORTED_LANGS)


def direction(lang: str | None = None) -> str:
    return "rtl" if (lang or get_lang()) == "ar" else "ltr"


def translate(key: str, **kwargs: object) -> str:
    lang = get_lang()
    text = TRANSLATIONS.get(lang, TRANSLATIONS[DEFAULT_LANG]).get(
        key, TRANSLATIONS[DEFAULT_LANG].get(key, key)
    )
    if kwargs:
        return text.format(**kwargs)
    return text


def translate_value(kind: str, value: object, fallback: str = "unknown") -> str:
    """Translate a display value without changing its stored/internal representation."""
    normalized = str(value or fallback).strip().lower().replace(" ", "_").replace("-", "_")
    prefixed = f"{kind}_{normalized}"
    catalog = TRANSLATIONS.get(get_lang(), TRANSLATIONS[DEFAULT_LANG])
    if prefixed in catalog:
        return translate(prefixed)
    if normalized in catalog:
        return translate(normalized)
    return str(value or translate(fallback))


def translate_status(value: object) -> str:
    return translate_value("status", value)


def translate_category(value: object) -> str:
    return translate_value("category", value)


def translate_vendor(value: object) -> str:
    return translate_value("vendor", value)


def translate_recommendation(value: object) -> str:
    return translate_value("rec", value)


def translate_guardrail(value: object) -> str:
    return translate_value("guardrail", value)


def translate_confidence(value: object) -> str:
    return translate_value("confidence", value)


def translate_decision(value: object) -> str:
    return translate_value("decision", value)


def translate_dynamic_text(value: object) -> str:
    """Translate service-generated display messages without changing service values."""
    text = str(value or "").strip()
    lowered = text.lower()
    exact = {
        "all required knowledge fields are valid": "diagnostic_schema_valid",
        "analyzer rule configuration is valid": "diagnostic_config_valid",
        "decision construction and confidence calculation operational": "diagnostic_decision_api",
        "recommendation threshold behavior validated": "diagnostic_recommendation_thresholds",
        "explanation creation operational": "diagnostic_explanation_api",
        "reason generation operational": "diagnostic_reason_generation",
        "no local analyzer rules matched": "no_local_analyzer_rules",
        "requires manual review confirmation": "manual_review_required",
        "manual review confirmation required": "manual_review_required",
        "undocumented reason": "undocumented_reason",
        "no known policy": "no_known_policy",
        "no analyzer reasons available": "no_analyzer_reasons",
    }
    if lowered in exact:
        return translate(exact[lowered])
    counted = (
        (r"^(\d+) knowledge entries loaded$", "diagnostic_entries_loaded"),
        (r"^(\d+) vendor groups loaded$", "diagnostic_vendor_groups"),
        (r"^(\d+) category groups loaded$", "diagnostic_category_groups"),
        (r"^(\d+) filter mappings loaded$", "diagnostic_filter_mappings"),
    )
    for pattern, key in counted:
        match = re.match(pattern, lowered)
        if match:
            return translate(key, count=match.group(1))
    if "unknown blocking policy" in lowered:
        return translate("policy_unknown_manual_review")
    if "no blocking policy is defined" in lowered:
        return translate("no_known_policy")
    if get_lang() == "ar" and re.search(r"[A-Za-z]{3,}", text):
        return translate("diagnostic_detail_unavailable")
    return text
